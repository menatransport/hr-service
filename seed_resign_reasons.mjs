const client = await new MongoClient(env.MONGO_URI).connect();
try {
  const db = client.db(env.MONGO_DB || "hr_service");
  const categories = db.collection("master_resign_category");
  const reasons = db.collection("master_resign_reason");
  await categories.createIndex({ prefix: 1 }, { name: "prefix_unique", unique: true });
  await reasons.createIndex({ code: 1 }, { name: "code_unique", unique: true });

  const stamp = { updatedAt: new Date().toISOString(), updatedBy: "seed (Reason Code Master_Final)" };
  let addedCat = 0;
  let addedCode = 0;

  for (const [ci, [prefix, label, exitType, rows]] of MASTER.entries()) {
    const catFields = { label, exitType, order: ci + 1, ...stamp };
    const cat = await categories.findOneAndUpdate(
      { prefix },
      RESET ? { $set: catFields } : { $setOnInsert: catFields },
      { upsert: true, returnDocument: "after", includeResultMetadata: true },
    );
    if (!cat.lastErrorObject?.updatedExisting) addedCat++;
    const categoryId = cat.value._id.toHexString();

    for (const [ri, [code, sub, description = "", own]] of rows.entries()) {
      const fields = {
        categoryId,
        label: sub,
        description,
        exitType: own ?? exitType,
        active: true,
        order: ri + 1,
        ...stamp,
      };
      const res = await reasons.updateOne(
        { code },
        RESET ? { $set: fields } : { $setOnInsert: fields },
        { upsert: true },
      );
      if (res.upsertedCount) addedCode++;
    }
  }

  const total = await reasons.countDocuments();
  console.log(
    `เสร็จแล้ว — หมวดใหม่ ${addedCat} · รหัสใหม่ ${addedCode} · รหัสทั้งหมดในฐานข้อมูล ${total}${RESET ? " (เขียนทับตาม Excel)" : ""}`,
  );
} finally {
  await client.close();
}
