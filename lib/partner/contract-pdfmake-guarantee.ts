export function guaranteeDocDef(c: Contract, promo: PromoMasterData | null): any {
  return docShell({
    fileTitle: `สัญญาค้ำประกัน-${c.contractCode}`,
    docTitle: "สัญญาค้ำประกัน",
    contractCode: c.contractCode,
    content: content(c, promo),
  })
}
