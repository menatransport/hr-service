export const effectOf = (itemId: string, column: string): MoneyEffect | undefined =>
  MONEY_COLUMNS[itemId]?.[column];

/** ช่องที่ลงสลิปจริงของรายการหนึ่ง (ไม่รวมอ้างอิง) */
export function postedColumns(itemId: string): { column: string; effect: MoneyEffect }[] {
  return Object.entries(MONEY_COLUMNS[itemId] ?? {})
    .filter(([, effect]) => effect !== "อ้างอิง")
    .map(([column, effect]) => ({ column, effect }));
}

export function kindOf(itemId: string): ItemKind {
  const posted = postedColumns(itemId);
  if (posted.length === 0) return "ฐาน";
  if (posted.some((p) => p.effect === "รอยืนยัน")) return "รอยืนยัน";
  const add = posted.some((p) => p.effect === "เพิ่ม");
  const cut = posted.some((p) => p.effect === "หัก");
  if (add && cut) return "ผสม";
  return add ? "เพิ่ม" : "หัก";
}

export interface ItemClassification {
  item: IntakeItem;
  kind: ItemKind;
  posted: { column: string; effect: MoneyEffect }[];
  payeeColumn: string;
  dataMonthOffset: { months: number; evidence: string } | null;
}

export function classify(itemId: string): ItemClassification | null {
  const item = findItem(itemId);
  if (!item) return null;
  return {
    item,
    kind: kindOf(itemId),
    posted: postedColumns(itemId),
    payeeColumn: PAYEE_COLUMN[itemId] ?? DEFAULT_PAYEE_COLUMN,
    dataMonthOffset: DATA_MONTH_OFFSET[itemId] ?? null,
  };
}

/* ------------------------------------------------------------------ ตรวจ */

/** ช่องที่ "หน้าตาเป็นตัวเลขเงิน" — ถ้าหลุดจาก `MONEY_COLUMNS` ต้องมีคนมาดู */
const LOOKS_LIKE_MONEY = /บาท|จำนวนเงิน|ยอด|หัก|รางวัล|Incentive|เบี้ย/i;

/**
 * ตรวจว่าการจัดประเภทกับสเปกคอลัมน์ยังตรงกัน — คืนรายการข้อผิดพลาด ว่างคือผ่าน
 *
 * ตรวจสองทาง: ช่องที่จัดประเภทไว้ต้องมีจริงในสเปก (กันสะกดเพี้ยน) และช่องในสเปก
 * ที่หน้าตาเป็นเงินต้องถูกจัดประเภท (กันเพิ่มช่องใหม่แล้วลืม) · ช่องเงินเข้าใครก็
 * ต้องมีจริงด้วย ไม่งั้นตัวอ่านไฟล์จะหาคอลัมน์ไม่เจอตอนจ่ายจริง
 */
export function validateClassification(): string[] {
  const problems: string[] = [];

  for (const item of INTAKE_ITEMS) {
    const spec = templateOf(item.id);
    if (!spec) {
      problems.push(`#${item.id} ไม่มีสเปกคอลัมน์`);
      continue;
    }
    const have = new Set(spec.columns);
    const classified = MONEY_COLUMNS[item.id] ?? {};

    for (const column of Object.keys(classified)) {
      if (!have.has(column)) {
        problems.push(`#${item.id} จัดประเภทช่อง “${column}” ไว้ แต่สเปกไม่มีช่องนี้`);
      }
    }
    for (const column of spec.columns) {
      if (LOOKS_LIKE_MONEY.test(column) && !(column in classified)) {
        problems.push(`#${item.id} ช่อง “${column}” หน้าตาเป็นเงิน แต่ยังไม่ได้จัดประเภท`);
      }
    }

    const payee = PAYEE_COLUMN[item.id] ?? DEFAULT_PAYEE_COLUMN;
    if (!have.has(payee)) {
      problems.push(`#${item.id} ช่องเงินเข้าใคร “${payee}” ไม่มีในสเปก`);
    }

  }

  for (const id of Object.keys(MONEY_COLUMNS)) {
    if (!findItem(id)) problems.push(`จัดประเภท #${id} ไว้ แต่ทะเบียนไม่มีรายการนี้`);
  }

  return problems;
}
