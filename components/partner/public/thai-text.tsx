/**
 * กันคำไทยแตกกลางคำตอนขึ้นบรรทัดใหม่
 * เบราว์เซอร์ตัดบรรทัดไทยด้วยพจนานุกรม คำทับศัพท์/ชื่อเฉพาะที่ไม่อยู่ในนั้นเลยโดนหั่นกลางคำ
 * (เจอจริง: "แพลนท์ปูน" → "แพลน / ท์ปูน") — ห่อคำกลุ่มนี้ด้วย nowrap ให้ตัดได้เฉพาะรอยต่อคำจริง
 * ฝั่ง PDF มีกลไกเดียวกันที่ lib/pdfmake-printer (COMPOUND_RE)
 */
const KEEP = [
  "แพล้นท์ปูน", "แพล้นท์", "แพลนท์ปูน", "แพลนท์", "ไฟแนนซ์", "มิกเซอร์", "โปรโมชั่น", "คอนกรีตผสมเสร็จ", "คอนกรีต",
  "ปูนซีเมนต์", "ทรานสปอร์ต", "รายเดือน", "ค่าเที่ยว", "ซ่อมบำรุง", "เจ้าของเดียว", "ทุกระยะ", "ทุกวัน", "ไฟแนนซ์ภายนอก",
]
const RE = new RegExp(`(${KEEP.join("|")})`, "g")

export function ThaiText({ children }: { children: string }) {
  return (
    <>
      {children.split(RE).map((part, i) =>
        KEEP.includes(part) ? <span key={i} className="whitespace-nowrap">{part}</span> : part,
      )}
    </>
  )
}

/** ลิงก์โทร — ตัดช่องว่าง/ขีดออกจากเบอร์ ("061 961 5364" → tel:0619615364) */
export const telHref = (phone: string) => `tel:${phone.replace(/[^0-9+]/g, "")}`
