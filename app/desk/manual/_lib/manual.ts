/** ภาพจำลองของหนึ่งส่วน — `bar` ใช้คำนำหน้า: `?` ช่องค้นหา · `+` ปุ่มหลัก · `x` ปุ่ม Excel · `#` ชิป */
export type Sketch =
  | { kind: "cards"; items: string[]; active?: number }
  | { kind: "bar"; items: string[] }
  | { kind: "tabs"; items: string[]; active?: number }
  | { kind: "table"; cols: string[] }
  | { kind: "split"; items: string[] }
  | { kind: "note"; text: string };

/** [ชื่อปุ่ม, กดแล้วเกิดอะไร, รายละเอียดย่อยเป็น bullet ซ้อน] */
export type Btn = [string, string, string[]?];

export interface Part {
  title: string;
  /** สิ่งที่เห็นในส่วนนี้ — หนึ่งข้อหนึ่ง bullet */
  points?: string[];
  sketch?: Sketch;
  buttons?: Btn[];
  /** ต้องมีสิทธิ์ย่อยนี้ถึงเห็นส่วนนี้ */
  perm?: string;
}

/** มุมมองเมื่อกดการ์ดสรุป (StatCard) หนึ่งใบ */
export interface CardView {
  label: string;
  /** เงื่อนไขที่ทำให้คนขึ้นการ์ดนี้ */
  rule: string;
  cols: string[];
  /** ใช้การ์ดนี้ทำอะไร */
  points?: string[];
  buttons?: Btn[];
}

export type Tone = "new" | "wait" | "live" | "done" | "ok" | "alert" | "pink";

export interface Manual {
  /** = id ของเมนูใน `lib/modules.ts` */
  id: string;
  summary: string;
  parts: Part[];
  /** อธิบายทีละการ์ดสรุป — กดการ์ดในคู่มือเพื่อดูว่าหน้าจอเปลี่ยนเป็นอะไร */
  cards?: CardView[];
  steps?: { title: string; items: string[]; perm?: string }[];
  statuses?: [string, Tone, string][];
  tips?: string[];
  /** ตัวอย่างประกอบเรื่องที่เข้าใจยาก — ขึ้นก่อน “ข้อควรรู้” */
  example?: { title: string; items: string[] };
  /** ป้ายเตือนบนสุดของหน้าคู่มือ (เช่น หน้ายังไม่พร้อม) */
  banner?: string;
}

