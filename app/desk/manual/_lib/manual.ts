export function lastUpdated(id: string): string | null {
  return CHANGELOG.find((v) => v.items.some(([m]) => m === id))?.date ?? null;
}

export function changesOf(id: string): { date: string; time: string; text: string }[] {
  return CHANGELOG.flatMap((v) =>
    v.items.filter(([m]) => m === id).map(([, text]) => ({ date: v.date, time: v.time, text })),
  );
}

