import { STATUS_LABEL, type ApplicationStatus } from "@/app/recruitment/_lib/types";

/**
 * ป้ายสถานะใบสมัคร — ใช้ทั้งตารางแอดมินและหน้าติดตามของผู้สมัคร
 *
 * แยกจาก `components/ui/status-badge.tsx` เพราะชุดสถานะคนละชุดกันคนละเรื่อง
 * (นั่นเป็นสถานะคำร้องของ พจส.) แต่ยืมชุดสี `st-*` ของธีมมาใช้ตัวเดียวกัน
 * หน้าจอทั้งระบบจึงอ่านป้ายสถานะด้วยสายตาชุดเดิม
 *
 * สีถูกแจกตาม **สิ่งที่ต้องทำต่อ** ไม่ใช่ตามลำดับขั้น: ฟ้า = ถึงคิวเราแล้ว (รอโทร)
 * · ส้ม = ลูกบอลอยู่ที่อีกฝั่ง รอเวลา (นัดแล้ว / รอผล) · เขียวเข้ม = ผ่านแล้ว
 * · **แดง = ยกเลิก** — แถวที่ยังไม่มีใครแตะจึงเด้งออกมาจากตาราง ไม่ใช่จมไป
 * กับแถวที่ปิดงานแล้ว
 *
 * “ยกเลิก” เป็นแดงไม่ใช่เทา เพราะเป็นตัวเลขที่ต้องมองเห็นว่าเดือนนี้เสียผู้สมัคร
 * ไปเท่าไหร่ ไม่ใช่ปลายทางที่ปล่อยให้จมหายไปเฉย ๆ
 */

/**
 * โทนมาจาก `@utility chip-*` ใน `globals.css` ไม่ใช่คู่ `bg-…`/`text-…` ที่
 * พิมพ์เองตรงนี้ — ป้ายจึงได้เส้นขอบของโทนนั้นติดมาด้วยโดยไม่ต้องจำว่าโทนไหน
 * คู่กับเส้นสีอะไร และแก้ชุดสีทั้งระบบได้จากไฟล์เดียว
 */
const TONE: Record<ApplicationStatus, string> = {
  pending_contact: "chip-new",
  interview_scheduled: "chip-wait",
  interview_waiting: "chip-wait",
  interview_passed: "chip-live",
  cancelled: "chip-alert",
  /* กำลังฝึก = ป้ายพื้นทึบตัวเดียวของชุด — เป็นสถานะที่ต้องหาเจอก่อนเพื่อนในตาราง */
  training: "chip-on",
  /* ปฏิบัติงาน = ส่งต่อให้ทะเบียน พจส. แล้ว ใบสมัครจบหน้าที่ — เทาแบบปิดงาน ไม่แย่งสายตาจากคนที่กำลังฝึก */
  working: "chip-done",
};

export function StatusPill({
  status,
  className = "",
}: {
  status: ApplicationStatus;
  className?: string;
}) {
  return (
    <span
      className={`chip ${TONE[status]} ${className}`}
    >
      {STATUS_LABEL[status]}
    </span>
  );
}
